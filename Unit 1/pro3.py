#Write a program to perform arithmetic relational and logical operations using Python operators.

num1=float(input("Enter first number:"))
num2=float(input("Enter second number:"))

#Arithmetic operators
print("Addition:",num1+ num2)
print("Substraction:",num1-num2)
print("Multiplication:",num1*num2)
print("Division:",num1/num2)
print("Modulus:",num1%num2)

#Relational Operators
print("Greater than:",num1>num2)
print("Less than:",num1<num2)
print("Equal to:",num1==num2)
print("Not equal to:",num1!=num2)

#Logical operators
a= True
b= False

print("Logical AND:",a and b)
print("Logical OR:",a or b)
print("Logical NOT:",not a)

