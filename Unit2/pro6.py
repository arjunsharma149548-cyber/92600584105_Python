#Write a program to iterate over lists strings and dictionaries using loops.

# List
numbers = [10, 20, 30, 40]

for i in numbers:
    print(i)

# String
name = "ARJUN"

for i in name:
    print(i)

# Dictionary
student = {"Name": "Arjun", "Age": 21}

for key, value in student.items():
    print(key, value)